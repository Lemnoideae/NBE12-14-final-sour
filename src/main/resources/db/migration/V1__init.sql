-- ---------------------------------------------------------------------
-- CREDIT_HISTORY (크레딧 원장, 수정·삭제하지 않음)
-- ---------------------------------------------------------------------
CREATE TABLE credit_history (
                                id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
                                user_id        BIGINT       NOT NULL,
                                payment_id     BIGINT,
                                user_item_id   BIGINT,
                                amount         BIGINT       NOT NULL,
                                balance_after  BIGINT       NOT NULL,
                                type           VARCHAR(20)  NOT NULL,
                                created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                CONSTRAINT pk_credit_history PRIMARY KEY (id),
                                CONSTRAINT fk_credit_history_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    -- 다른 회원의 결제·구매에 연결되지 않도록 복합 FK. payment_id·user_item_id가 NULL이면 검사하지 않는다
                                CONSTRAINT fk_credit_history_payment FOREIGN KEY (payment_id, user_id)
                                    REFERENCES payment (id, user_id) ON DELETE RESTRICT,
                                CONSTRAINT fk_credit_history_user_item FOREIGN KEY (user_item_id, user_id)
                                    REFERENCES user_item (id, user_id) ON DELETE RESTRICT,
    -- 결제 1건에 충전 1번, 구매 1건에 차감 1번 (웹훅 중복·재시도로 두 번 쌓이지 않음)
                                CONSTRAINT uk_credit_history_payment UNIQUE (payment_id),
                                CONSTRAINT uk_credit_history_user_item UNIQUE (user_item_id),
                                CONSTRAINT ck_credit_history_type CHECK (type IN ('CHARGE', 'USE')),
    -- CHARGE는 결제에만, USE는 구매에만 연결된다
                                CONSTRAINT ck_credit_history_source CHECK (
                                    (type = 'CHARGE' AND payment_id IS NOT NULL AND user_item_id IS NULL)
                                        OR (type = 'USE' AND user_item_id IS NOT NULL AND payment_id IS NULL)
                                    ),
    -- 금액은 항상 양수, 방향은 type으로 구분
                                CONSTRAINT ck_credit_history_amount CHECK (amount > 0),
                                CONSTRAINT ck_credit_history_balance_after CHECK (balance_after >= 0)
);
CREATE INDEX idx_credit_history_user_created ON credit_history (user_id, created_at DESC);
COMMENT ON TABLE credit_history IS '크레딧 충전·사용 원장. 증감 1건 = 1행. 수정·삭제하지 않으므로 updated_at 없음';
COMMENT ON COLUMN credit_history.amount IS '증감량 (항상 양수). CHARGE = +, USE = -';
COMMENT ON COLUMN credit_history.balance_after IS '이 행을 반영한 뒤 users.credit_balance';


