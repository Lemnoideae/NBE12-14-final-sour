-- ---------------------------------------------------------------------
-- USER (user는 PostgreSQL 예약어이므로 users)
-- ---------------------------------------------------------------------
CREATE TABLE users (
                       id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
                       university_id        BIGINT        NOT NULL,
                       department_id        BIGINT        NOT NULL,
                       clicker_id           BIGINT        NOT NULL DEFAULT 1,
                       credit_balance       BIGINT        NOT NULL DEFAULT 0,
                       role                 VARCHAR(20)   NOT NULL DEFAULT 'USER',
                       nickname             VARCHAR(30)   NOT NULL,
                       email                VARCHAR(512)  NOT NULL,
                       email_hash           VARCHAR(64)   NOT NULL,
                       password             VARCHAR(100)  NOT NULL,
                       approved_at          TIMESTAMPTZ   NOT NULL,
                       total_contrib_score  BIGINT        NOT NULL DEFAULT 0,
                       total_attack_score   BIGINT        NOT NULL DEFAULT 0,
                       logo_url             VARCHAR(500),
                       status               VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
                       created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       deleted_at           TIMESTAMPTZ,
                       CONSTRAINT pk_users PRIMARY KEY (id),
                       CONSTRAINT fk_users_university FOREIGN KEY (university_id) REFERENCES university (id) ON DELETE RESTRICT,
    -- 학과가 소속 학교의 학과인지 DB에서 확인
                       CONSTRAINT fk_users_department FOREIGN KEY (department_id, university_id)
                           REFERENCES department (id, university_id) ON DELETE RESTRICT,
                       CONSTRAINT fk_users_clicker FOREIGN KEY (clicker_id) REFERENCES clicker (id) ON DELETE RESTRICT,
                       CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
                       CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'BANNED', 'WITHDRAWN')),
                       CONSTRAINT ck_users_email_hash CHECK (email_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_users_total_contrib_score CHECK (total_contrib_score >= 0),
    CONSTRAINT ck_users_total_attack_score CHECK (total_attack_score >= 0),
    CONSTRAINT ck_users_credit_balance CHECK (credit_balance >= 0),
    CONSTRAINT ck_users_withdrawn CHECK ((status = 'WITHDRAWN') = (deleted_at IS NOT NULL))
);
-- 이메일·닉네임은 탈퇴하지 않은 회원끼리만 유일하다.
-- 탈퇴하면 같은 이메일로 새 회원 가입이 가능하고, 닉네임도 다시 쓸 수 있다.
CREATE UNIQUE INDEX uk_users_email_hash ON users (email_hash) WHERE deleted_at IS NULL;
-- MySQL utf8mb4_unicode_ci처럼 대소문자를 구분하지 않는 닉네임 유일성
CREATE UNIQUE INDEX uk_users_nickname_ci ON users (lower(nickname)) WHERE deleted_at IS NULL;
CREATE INDEX idx_users_university_contrib ON users (university_id, total_contrib_score DESC);
CREATE INDEX idx_users_department ON users (department_id);
COMMENT ON TABLE users IS '회원 정보 및 개인 기여도';
COMMENT ON COLUMN users.email IS '학교 이메일 (암호화 저장)';
COMMENT ON COLUMN users.email_hash IS '정규화한 이메일의 SHA-256 (소문자 hex 64자). 탈퇴하지 않은 회원끼리 유일';
COMMENT ON COLUMN users.credit_balance IS '보유 크레딧 (1원 = 1크레딧). DB가 원본이고 Redis에 두지 않음. 증감은 조건부 UPDATE + CREDIT_HISTORY INSERT를 한 트랜잭션에서 처리';
COMMENT ON COLUMN users.total_contrib_score IS '기여 점수 (순위·재화 겸용, 아이템 구매·클리커 업그레이드 시 차감). Redis가 원본이고 1분마다 배치로 반영';


