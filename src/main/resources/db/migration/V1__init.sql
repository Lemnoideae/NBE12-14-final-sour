-- =====================================================================
-- 대대대 PostgreSQL 스키마
-- 기준 문서: ERD 상세 (PostgreSQL 버전)
-- 대상: PostgreSQL 16 (AWS RDS)
-- Flyway를 쓰면 이 파일을 V1__init.sql로 그대로 사용할 수 있다.
--
-- 이름 규칙
--   pk_{테이블}            기본키
--   fk_{테이블}_{대상}     외래키
--   uk_{테이블}_{내용}     유니크 제약·유니크 인덱스
--   ck_{테이블}_{내용}     CHECK 제약
--   idx_{테이블}_{내용}    조회용 인덱스
-- 제약 이름은 에러 응답에 그대로 실려 오므로(SQLSTATE 23505 / 23514 + constraint name)
-- 애플리케이션에서 API 에러 코드로 바꿀 때 사용한다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 공통: updated_at 자동 갱신
-- MySQL의 ON UPDATE CURRENT_TIMESTAMP를 대신한다.
-- MySQL과 같게, 실제로 값이 바뀐 행만 updated_at을 바꾼다.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD THEN
        NEW.updated_at := now();
END IF;
RETURN NEW;
END;
$$;


