CREATE UNIQUE INDEX uk_alliance_match_requested_pair
    ON alliance_match (LEAST(alliance_a_id, alliance_b_id), GREATEST(alliance_a_id, alliance_b_id))
    WHERE status = 'REQUESTED' AND deleted_at IS NULL;
-- 종료 대상 대결 조회 (스케줄러)
CREATE INDEX idx_alliance_match_in_progress_ended ON alliance_match (ended_at) WHERE status = 'IN_PROGRESS';
-- 신청 마감 지난 대결 조회 (스케줄러)
CREATE INDEX idx_alliance_match_requested_expire ON alliance_match (request_expired_at) WHERE status = 'REQUESTED';
-- 연합별 대결 이력 조회
CREATE INDEX idx_alliance_match_alliance_a ON alliance_match (alliance_a_id);
CREATE INDEX idx_alliance_match_alliance_b ON alliance_match (alliance_b_id);
COMMENT ON TABLE alliance_match IS '연합 간 대결 (2:2만, 두 연합이 만료되기 전에 끝나야 함)';


-- ---------------------------------------------------------------------
-- 대결은 반드시 두 연합이 만료되기 전에 끝나야 한다
-- 연합 만료 시각은 만든 뒤 바뀌지 않으므로 대결 쪽에서만 확인하면 된다.
--   ck_alliance_match_within_alliance : 종료 시각이 두 연합 중 빠른 만료 시각보다 늦음
--   ck_alliance_match_request_deadline: 대기 중인 신청을 마감 시각에 수락해도 연합 만료 전에 끝나지 않음
-- 위반하면 SQLSTATE 23514(check_violation)와 위 제약 이름으로 에러가 난다.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_alliance_match_within_alliance() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
v_expired_at TIMESTAMPTZ;
BEGIN
SELECT min(expired_at) INTO v_expired_at
FROM alliance
WHERE id IN (NEW.alliance_a_id, NEW.alliance_b_id);

IF NEW.ended_at IS NOT NULL AND NEW.ended_at > v_expired_at THEN
        RAISE EXCEPTION '대결 종료 시각(%)이 연합 만료 시각(%)보다 늦습니다', NEW.ended_at, v_expired_at
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_alliance_match_within_alliance';
END IF;

    IF NEW.status = 'REQUESTED'
       AND NEW.request_expired_at + NEW.duration_hours * INTERVAL '1 hour' > v_expired_at THEN
        RAISE EXCEPTION '신청 마감(%)에 수락하면 연합 만료 시각(%) 뒤에 끝납니다', NEW.request_expired_at, v_expired_at
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_alliance_match_request_deadline';
END IF;

RETURN NEW;
END;
$$;

CREATE TRIGGER trg_alliance_match_within_alliance
    BEFORE INSERT OR UPDATE OF alliance_a_id, alliance_b_id, status, started_at, ended_at, duration_hours, request_expired_at
                     ON alliance_match
                         FOR EACH ROW EXECUTE FUNCTION check_alliance_match_within_alliance();


