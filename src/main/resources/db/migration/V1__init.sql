CREATE TABLE alliance_match (
                                id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
                                alliance_a_id       BIGINT       NOT NULL,
                                alliance_b_id       BIGINT       NOT NULL,
                                winner_alliance_id  BIGINT,
                                started_at          TIMESTAMPTZ,
                                ended_at            TIMESTAMPTZ,
                                duration_hours      INTEGER      NOT NULL,
                                request_expired_at  TIMESTAMPTZ  NOT NULL,
                                status              VARCHAR(20)  NOT NULL DEFAULT 'REQUESTED',
                                a_score             BIGINT       NOT NULL DEFAULT 0,
                                b_score             BIGINT       NOT NULL DEFAULT 0,
                                created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                deleted_at          TIMESTAMPTZ,
                                CONSTRAINT pk_alliance_match PRIMARY KEY (id),
                                CONSTRAINT fk_alliance_match_alliance_a FOREIGN KEY (alliance_a_id) REFERENCES alliance (id) ON DELETE RESTRICT,
                                CONSTRAINT fk_alliance_match_alliance_b FOREIGN KEY (alliance_b_id) REFERENCES alliance (id) ON DELETE RESTRICT,
                                CONSTRAINT fk_alliance_match_winner FOREIGN KEY (winner_alliance_id) REFERENCES alliance (id) ON DELETE RESTRICT,
                                CONSTRAINT ck_alliance_match_different CHECK (alliance_a_id <> alliance_b_id),
                                CONSTRAINT ck_alliance_match_status CHECK (status IN ('REQUESTED', 'IN_PROGRESS', 'FINISHED', 'CANCELED')),
    -- 대결 기간 1~24시간
                                CONSTRAINT ck_alliance_match_duration_hours CHECK (duration_hours BETWEEN 1 AND 24),
    -- 수락하면 종료 시각 = 시작 시각 + 신청한 기간
                                CONSTRAINT ck_alliance_match_duration CHECK (ended_at - started_at = duration_hours * INTERVAL '1 hour'),
    -- 수락된 대결은 시작·종료 시각이 있어야 한다
    CONSTRAINT ck_alliance_match_period CHECK (status IN ('REQUESTED', 'CANCELED') OR (started_at IS NOT NULL AND ended_at IS NOT NULL)),
    -- 승자는 FINISHED일 때만, A 또는 B 중 하나
    CONSTRAINT ck_alliance_match_winner CHECK (
        winner_alliance_id IS NULL
        OR (status = 'FINISHED' AND winner_alliance_id IN (alliance_a_id, alliance_b_id))
    ),
    CONSTRAINT ck_alliance_match_a_score CHECK (a_score >= 0),
    CONSTRAINT ck_alliance_match_b_score CHECK (b_score >= 0)
);
