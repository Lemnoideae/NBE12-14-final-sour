CREATE TABLE university (
                            id           BIGINT        GENERATED BY DEFAULT AS IDENTITY,
                            name         VARCHAR(100)  NOT NULL,
                            total_score  BIGINT        NOT NULL DEFAULT 0,
                            library_lat  NUMERIC(9,6),
                            library_lng  NUMERIC(9,6),
                            logo_url     VARCHAR(500),
                            created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                            updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                            CONSTRAINT pk_university PRIMARY KEY (id),
                            CONSTRAINT uk_university_name UNIQUE (name),
                            CONSTRAINT ck_university_total_score CHECK (total_score >= 0),
                            CONSTRAINT ck_university_library_lat CHECK (library_lat BETWEEN -90 AND 90),
                            CONSTRAINT ck_university_library_lng CHECK (library_lng BETWEEN -180 AND 180),
                            CONSTRAINT ck_university_library_pair CHECK ((library_lat IS NULL) = (library_lng IS NULL))
);
CREATE INDEX idx_university_total_score ON university (total_score DESC);
COMMENT ON TABLE university IS '학교 정보 및 학교 누적 점수';


