-- ---------------------------------------------------------------------
-- PAYMENT (토스페이먼츠 크레딧 충전)
-- ---------------------------------------------------------------------
CREATE TABLE payment (
                         id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
                         order_id       VARCHAR(64)   NOT NULL,
                         order_name     VARCHAR(100)  NOT NULL,
                         user_id        BIGINT        NOT NULL,
                         amount         BIGINT        NOT NULL,
                         status         VARCHAR(20)   NOT NULL DEFAULT 'READY',
                         payment_key    VARCHAR(200),
                         method         VARCHAR(20),
                         fail_code      VARCHAR(100),
                         fail_message   VARCHAR(255),
                         cancel_reason  VARCHAR(200),
                         requested_at   TIMESTAMPTZ,
                         approved_at    TIMESTAMPTZ,
                         canceled_at    TIMESTAMPTZ,
                         created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
                         updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
                         CONSTRAINT pk_payment PRIMARY KEY (id),
                         CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
                         CONSTRAINT uk_payment_order_id UNIQUE (order_id),
                         CONSTRAINT uk_payment_payment_key UNIQUE (payment_key),
    -- credit_history의 복합 FK(payment_id, user_id)가 참조하는 대상
                         CONSTRAINT uk_payment_id_user UNIQUE (id, user_id),
    -- 토스 orderId 규칙: 6~64자, 영문·숫자·-·_·=
                         CONSTRAINT ck_payment_order_id CHECK (order_id ~ '^[A-Za-z0-9_=-]{6,64}$'),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('READY', 'IN_PROGRESS', 'DONE', 'ABORTED', 'EXPIRED', 'CANCELED')),
    CONSTRAINT ck_payment_done CHECK (status NOT IN ('DONE', 'CANCELED') OR (payment_key IS NOT NULL AND approved_at IS NOT NULL)),
    CONSTRAINT ck_payment_canceled CHECK (status <> 'CANCELED' OR canceled_at IS NOT NULL)
);
CREATE INDEX idx_payment_user_created ON payment (user_id, created_at DESC);
-- 미완료 결제 정리 배치용. 끝난 결제는 인덱스에 들어가지 않는다.
CREATE INDEX idx_payment_unfinished ON payment (status, created_at) WHERE status IN ('READY', 'IN_PROGRESS');
COMMENT ON TABLE payment IS '크레딧 충전 결제 (토스페이먼츠). 결제 1건 = 1행. 환불 기능 없음';
COMMENT ON COLUMN payment.order_name IS '토스 orderName (예: 크레딧 5,000)';
COMMENT ON COLUMN payment.amount IS '결제 금액 (원) = 충전 크레딧 (1원 = 1크레딧)';


